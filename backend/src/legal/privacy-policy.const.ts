export const PRIVACY_POLICY_UPDATED_AT = '2026-08-20';

export function privacyPolicyVersionFor(html: string): string {
  return `2026-08-20-draft+${createHash('sha256')
    .update(html)
    .digest('hex')
    .slice(0, 8)}`;
}

// Хеш нужен, чтобы текст физически нельзя было поменять, «забыв» поднять
// версию: любая правка сама делает прошлые согласия неактуальными. Суффикс
// -draft означает, что текст ещё не является юридической редакцией (§2.1).
export const PRIVACY_POLICY_VERSION = privacyPolicyVersionFor(
  PRIVACY_POLICY_HTML,
);
